const FALLBACK_TIP = TIPS_AFTER_PROGRAM[0] as string;

export function getDailyTip(rawDayNumber: number): string {
  if (rawDayNumber >= 1 && rawDayNumber <= DRIP_CAMPAIGN.length) {
    return DRIP_CAMPAIGN[rawDayNumber - 1]?.insightText ?? FALLBACK_TIP;
  }
  const index = (rawDayNumber - DRIP_CAMPAIGN.length - 1) % TIPS_AFTER_PROGRAM.length;
  return TIPS_AFTER_PROGRAM[index] ?? FALLBACK_TIP;
}
